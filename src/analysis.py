# Answer the two questions of the study and write the results in reports/results.md.
# Run from the project root, after src/build_film_year_table.py:
#   python src/analysis.py
#
# Q1: does the average rating of the winner fall more slowly than the ratings of the other nominees of its ceremony?
# Q2: does the position of the winner among the nominees of its ceremony get better or worse over time?
# Main analysis: from the ceremony year to 5 years later. Complementary analysis: from the ceremony year to 2022.

import numpy as np
import pandas as pd
import statsmodels.api as sm
from scipy import stats

MAIN_FILE = "data/processed/film_year_window.csv"
LONG_FILE = "data/processed/film_year_until_2022.csv"
RESULTS_FILE = "reports/results.md"
LAST_FULL_YEAR = 2022


def film_slopes(table, weighted=True):
    # One slope per film: how much its yearly average rating changes per year.
    # Each year is weighted by its number of ratings. A film needs at least 3 yearly rows.
    films = table[["movieId", "title", "ceremony_year", "is_winner"]].drop_duplicates()
    results = []
    for movie_id, rows in table.groupby("movieId"):
        if len(rows) < 3:
            continue
        X = sm.add_constant(rows["years_since_ceremony"])
        weights = rows["nb_ratings"] if weighted else np.ones(len(rows))
        fit = sm.WLS(rows["avg_rating"], X, weights=weights).fit()
        results.append({"movieId": movie_id, "slope": fit.params["years_since_ceremony"]})
    return films.merge(pd.DataFrame(results), on="movieId")


def winner_minus_others(slopes):
    # One difference per ceremony: slope of the winner minus the mean slope of the other nominees.
    differences = []
    for ceremony, group in slopes.groupby("ceremony_year"):
        winner = group.loc[group["is_winner"], "slope"]
        others = group.loc[~group["is_winner"], "slope"]
        if len(winner) == 1 and len(others) >= 1:
            differences.append(winner.iloc[0] - others.mean())
    return pd.Series(differences)


def test_against(values, reference=0):
    # t-test of the mean of the values against a reference, with the 95% confidence interval.
    test = stats.ttest_1samp(values, reference)
    low, high = test.confidence_interval(confidence_level=0.95)
    return {"mean": values.mean(), "t": test.statistic, "p": test.pvalue, "low": low, "high": high}


def sign_counts(values):
    # Number of negative and positive values, and the p-value of the sign test.
    n_negative = int((values < 0).sum())
    n_positive = int((values > 0).sum())
    p_value = stats.binomtest(n_negative, n_negative + n_positive, 0.5).pvalue
    return n_negative, n_positive, p_value


def normalised_ranks(rows):
    # Rank of every nominee inside its ceremony (1 = best average rating), then rescaled:
    # 1 = best rated, 0 = worst rated, 0.5 = middle. Ties get the average of their ranks.
    group = rows.groupby("ceremony_year")["avg_rating"]
    rank = group.rank(ascending=False, method="average")
    n_nominees = group.transform("count")
    return rows.assign(normalised_rank=(n_nominees - rank) / (n_nominees - 1))


def winner_position(table, end_mask):
    # Normalised rank of the winner at the start (ceremony year) and at the end, and the change.
    start = normalised_ranks(table[table["years_since_ceremony"] == 0])
    end = normalised_ranks(table[end_mask])
    start_winner = start[start["is_winner"]].set_index("ceremony_year")["normalised_rank"]
    end_winner = end[end["is_winner"]].set_index("ceremony_year")["normalised_rank"]
    positions = pd.DataFrame({"start": start_winner, "end": end_winner}).dropna()
    positions["change"] = positions["end"] - positions["start"]
    return positions


def p_text(p_value):
    return "<0.001" if p_value < 0.001 else f"{p_value:.3f}"


def q2_row(label, quantity, result):
    return (f"| {label} | {quantity} | {result['mean']:+.4f} | {result['t']:.2f} | {p_text(result['p'])} | "
            f"{result['low']:+.4f} to {result['high']:+.4f} |")


main = pd.read_csv(MAIN_FILE)
long_table = pd.read_csv(LONG_FILE)
report = ["# Results", "", "Generated by `src/analysis.py`. All numbers are computed from the processed tables.", ""]

# ---------- Question 1 ----------
rule_tables = [
    ("Main: weights = number of ratings, all rows, ceremony year to +5", main, True),
    ("Robustness A: no weights", main, False),
    ("Robustness B: only rows with at least 100 ratings", main[main["nb_ratings"] >= 100], True),
    ("Complementary: ceremony year to 2022, weighted", long_table, True),
]
report += ["## Question 1: slope of the winner minus slope of the other nominees (rating points per year)", "",
           "| Rule | Ceremonies | Mean difference | t | p-value | 95% interval | Winner declines faster / slower | Sign test p |",
           "|---|---|---|---|---|---|---|---|"]
q1 = {}
for label, table, weighted in rule_tables:
    differences = winner_minus_others(film_slopes(table, weighted))
    result = test_against(differences)
    n_negative, n_positive, sign_p = sign_counts(differences)
    q1[label] = result
    report.append(f"| {label} | {len(differences)} | {result['mean']:+.4f} | {result['t']:.2f} | {p_text(result['p'])} | "
                  f"{result['low']:+.4f} to {result['high']:+.4f} | {n_negative} / {n_positive} | {sign_p:.3f} |")

# the numbers of the main analysis must match the notebook
main_result = q1[rule_tables[0][0]]
assert abs(main_result["mean"] - (-0.0137)) < 0.0001 and abs(main_result["p"] - 0.068) < 0.001

# ---------- Question 2 ----------
report += ["", "## Question 2: normalised rank of the winner among the nominees (1 = best rated, 0 = worst, 0.5 = middle)", "",
           "| Analysis | Quantity | Mean | t | p-value | 95% interval |", "|---|---|---|---|---|---|"]
q2_runs = [
    ("Main: ceremony year and 5 years later", winner_position(main, main["years_since_ceremony"] == 5)),
    ("Complementary: ceremony year and 2022", winner_position(long_table, long_table["rating_year"] == LAST_FULL_YEAR)),
]
q2_notes = []
for label, positions in q2_runs:
    report.append(q2_row(label, "rank at the start (compared with 0.5)", test_against(positions["start"], 0.5)))
    report.append(q2_row(label, "rank at the end (compared with 0.5)", test_against(positions["end"], 0.5)))
    report.append(q2_row(label, "change, end - start (compared with 0)", test_against(positions["change"], 0)))
    n_negative, n_positive, sign_p = sign_counts(positions["change"])
    q2_notes.append(f"- {label}: {len(positions)} ceremonies; position gets worse in {n_negative}, better in {n_positive}, "
                    f"unchanged in {int((positions['change'] == 0).sum())}; sign test p = {sign_p:.3f}.")
report += [""] + q2_notes

last_year_rows = long_table[long_table["rating_year"] == LAST_FULL_YEAR]
report += ["", f"Complementary analysis, rank in {LAST_FULL_YEAR}: {len(last_year_rows)} of {long_table['movieId'].nunique()} nominees have ratings that year, "
           f"and {int((last_year_rows['nb_ratings'] < 100).sum())} of them have fewer than 100 ratings, so these ranks are noisier than in the main analysis."]

# the numbers of the main analysis must match the notebook
main_positions = q2_runs[0][1]
assert abs(main_positions["start"].mean() - 0.738) < 0.001 and abs(main_positions["end"].mean() - 0.643) < 0.001

with open(RESULTS_FILE, "w") as file:
    file.write("\n".join(report) + "\n")

print("\n".join(report))
print(f"\nResults written to {RESULTS_FILE}")
